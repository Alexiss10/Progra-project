    public void actualizarTabla() {

        modeloTabla.setRowCount(0);

        for (Tela tela : gestorTelas.listar()) {

            modeloTabla.addRow(new Object[]{tela.getIdTela(), tela.getCodigo(), tela.getNombre(), tela.getDescripcion()});
        }
    }

