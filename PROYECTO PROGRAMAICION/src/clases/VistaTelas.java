    private void tblTelasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblTelasMouseClicked

        int filaSeleccionada = tblTelas.getSelectedRow();

        if (filaSeleccionada == -1) {
            return;
        }

        int filaModelo = tblTelas.convertRowIndexToModel(filaSeleccionada);

        int idTela = Integer.parseInt(
                modeloTabla.getValueAt(filaModelo, 0).toString());

        Tela tela = gestorTelas.buscarTelaPorId(idTela);

        if (tela == null) {
            limpiarCampos();

            JOptionPane.showMessageDialog(this,
                    "La tela seleccionada ya no está disponible.");

            actualizarTabla();
            return;
        }

        idTelaSeleccionada = tela.getIdTela();

        txtCodigo.setText(tela.getCodigo());
        txtNombre.setText(tela.getNombre());
        txtDescripcion.setText(tela.getDescripcion());
    }//GEN-LAST:event_tblTelasMouseClicked

    private void formWindowClosing(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowClosing
        if (!cambiosPendientes) {
            dispose();
            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(this,
                "¿Deseas guardar los cambios antes de salir?",
                "Guardar cambios", JOptionPane.YES_NO_OPTION);

        if (respuesta == JOptionPane.YES_OPTION) {

            try {

                gestorTelas.guardarCambios();
                cambiosPendientes = false;
                dispose();

            } catch (IOException | IllegalArgumentException e) {

                JOptionPane.showMessageDialog(this,
                        "No se pudieron guardar los cambios: " + e.getMessage(),
                        "Error de guardado", JOptionPane.ERROR_MESSAGE);
            }

        } else if (respuesta == JOptionPane.NO_OPTION) {

            dispose();
        }
    }//GEN-LAST:event_formWindowClosing

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

        if (idTelaSeleccionada == null) {
            JOptionPane.showMessageDialog(this,
                    "Primero busca o selecciona la tela que deseas eliminar.");
            return;
        }

        Tela tela = gestorTelas.buscarTelaPorId(idTelaSeleccionada);

        if (tela == null) {
            JOptionPane.showMessageDialog(this,
                    "La tela seleccionada ya no existe.");

            actualizarTabla();
            limpiarCampos();
            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(this,
                "¿Deseas eliminar la tela " + tela.getNombre() + "?",
                "Eliminar tela", JOptionPane.YES_NO_OPTION);

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        try {

            gestorTelas.eliminar(idTelaSeleccionada);
            cambiosPendientes = true;

            actualizarTabla();
            limpiarCampos();

            JOptionPane.showMessageDialog(this, "Tela eliminada de la sesión. "
                    + "Presiona Guardar cambios para conservar la eliminación.");

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(this, e.getMessage(),
                    "Error al eliminar", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void limpiarCampos() {

        idTelaSeleccionada = null;

        txtCodigo.setText("");
        txtNombre.setText("");
        txtDescripcion.setText("");

        tblTelas.clearSelection();
        txtCodigo.requestFocusInWindow();
    }

