    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {
            idTelaSeleccionada = null;
            tblTelas.clearSelection();

            Tela tela = gestorTelas.buscarPorCodigo(txtCodigo.getText());

            if (tela == null) {
                JOptionPane.showMessageDialog(this, "No existe una tela con ese código.");
                return;
            }

            idTelaSeleccionada = tela.getIdTela();
            txtCodigo.setText(tela.getCodigo());
            txtNombre.setText(tela.getNombre());
            txtDescripcion.setText(tela.getDescripcion());

        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "No se pudo buscar", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        if (idTelaSeleccionada == null) {
            JOptionPane.showMessageDialog(this, "Primero busca o selecciona la tela que deseas modificar.");    
            return;
        }

        try {
            gestorTelas.modificar(idTelaSeleccionada, txtCodigo.getText(), txtNombre.getText(), txtDescripcion.getText());

            actualizarTabla();
            limpiarCampos();

            JOptionPane.showMessageDialog(this, "Tela modificada. Presiona Guardar para conservar los cambios.");

        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "No se pudo modificar", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idTelaSeleccionada == null) {
            JOptionPane.showMessageDialog(this, "Primero busca o selecciona la tela que deseas eliminar.");
            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(this, "¿Deseas eliminar la tela seleccionada?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            gestorTelas.eliminar(idTelaSeleccionada);

            actualizarTabla();
            limpiarCampos();

            JOptionPane.showMessageDialog(this, "Tela eliminada. Presiona Guardar para conservar los cambios.");

        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "No se pudo eliminar", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (!gestorTelas.hayCambiosPendientes()) {
            JOptionPane.showMessageDialog(this, "No hay cambios pendientes para guardar.");
            return;
        }

        try {
            gestorTelas.guardarCambios();

            JOptionPane.showMessageDialog(this, "Cambios guardados correctamente.");

        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "No se pudieron guardar los cambios: " + ex.getMessage(), "Error de guardado", JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_btnGuardarActionPerformed

    private void tblTelasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblTelasMouseClicked
        int fila = tblTelas.getSelectedRow();

        if (fila == -1) {
            return;
        }

        int filaModelo = tblTelas.convertRowIndexToModel(fila);
        int idTela = (Integer) modeloTabla.getValueAt(filaModelo, 0);

        Tela tela = gestorTelas.buscarTelaPorId(idTela);

        if (tela == null) {
            limpiarCampos();
            actualizarTabla();
            JOptionPane.showMessageDialog(this, "La tela seleccionada ya no existe.");
            return;
        }

        idTelaSeleccionada = tela.getIdTela();
        txtCodigo.setText(tela.getCodigo());
        txtNombre.setText(tela.getNombre());
        txtDescripcion.setText(tela.getDescripcion());
    }//GEN-LAST:event_tblTelasMouseClicked


