    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed

        try {
            gestorTelas.registrar(txtCodigo.getText(), txtNombre.getText(), txtDescripcion.getText());

            actualizarTabla();
            limpiarCampos();

            JOptionPane.showMessageDialog(this, "Tela registrada. Presiona Guardar para conservar los cambios.");
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "No se pudo registrar", JOptionPane.WARNING_MESSAGE);
        }

    }//GEN-LAST:event_btnRegistrarActionPerformed

